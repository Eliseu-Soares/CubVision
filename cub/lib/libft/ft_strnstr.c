#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	i;
	size_t	j;

	i = 0;
	if (!*little || !little)
		return ((char *)big);
	while (big && big[i] && i < len)
	{
		j = 0;
		while (big[i + j] == little[j] && (i + j) < len)
			j++;
		if (j == ft_strlen(little) && j > 0)
			return ((char *)(&big[i]));
		i++;
	}
	return (NULL);
}
